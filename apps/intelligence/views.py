class ModelVersionViewSet(viewsets.ReadOnlyModelViewSet):
    """List and retrieve AI model versions.

    By default returns only active versions.  Pass ``?all=1`` to see
    every version ever registered.
    """

    serializer_class = ModelVersionSerializer
    permission_classes = [IsAuthenticated]

    def get_queryset(self):
        qs = ModelVersion.objects.annotate(
            prediction_count=Count("predictions")
        ).order_by("model_type", "-created_at")

        if not self.request.query_params.get("all"):
            qs = qs.filter(is_active=True)
        return qs


