# DemandForecast
# ===================================================================


class DemandForecastViewSet(viewsets.ReadOnlyModelViewSet):
    """Per-product demand forecasts generated by the prediction engine.

    Filters
    -------
    * ``product`` -- UUID of a catalog.Product
    * ``from_date`` / ``to_date`` -- ISO date range on ``forecast_date``
    * ``method`` -- forecasting method name
    """

    serializer_class = DemandForecastSerializer
    permission_classes = [IsAuthenticated]

    def get_queryset(self):
        qs = (
            DemandForecast.objects.select_related("product", "model_version")
            .order_by("-forecast_date", "-predicted_quantity")
        )

        product = self.request.query_params.get("product")
        if product:
            qs = qs.filter(product_id=product)

        from_date = self.request.query_params.get("from_date")
        if from_date:
            qs = qs.filter(forecast_date__gte=from_date)

        to_date = self.request.query_params.get("to_date")
        if to_date:
            qs = qs.filter(forecast_date__lte=to_date)

        method = self.request.query_params.get("method")
        if method:
            qs = qs.filter(method=method)

        return qs


