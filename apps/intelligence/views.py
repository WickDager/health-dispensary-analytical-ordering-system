class AnomalyAlertViewSet(viewsets.ModelViewSet):
    """Detected statistical anomalies.

    Read-write for resolution.  By default returns only unresolved alerts.
    Pass ``?all=1`` to include resolved items.

    Filters
    -------
    * ``anomaly_type`` -- e.g. ``unusual_order``, ``stock_discrepancy``
    * ``severity`` -- ``low`` / ``medium`` / ``high`` / ``critical``
    * ``subject_type`` -- e.g. ``product``, ``supplier``, ``order``
    * ``resolved`` -- ``true`` or ``false``
    """

    serializer_class = AnomalyAlertSerializer
    permission_classes = [IsAuthenticated, _ADMIN_PHARM_WRITE]

    def get_queryset(self):
        qs = AnomalyAlert.objects.select_related(
            "resolved_by"
        ).order_by("-created_at")

        if not self.request.query_params.get("all"):
            qs = qs.filter(resolved=False)

        anomaly_type = self.request.query_params.get("anomaly_type")
        if anomaly_type:
            qs = qs.filter(anomaly_type=anomaly_type)

        severity = self.request.query_params.get("severity")
        if severity:
            qs = qs.filter(severity=severity)

        subject_type = self.request.query_params.get("subject_type")
        if subject_type:
            qs = qs.filter(subject_type=subject_type)

        resolved_param = self.request.query_params.get("resolved")
        if resolved_param is not None:
            qs = qs.filter(resolved=resolved_param.lower() == "true")

        return qs

    @action(detail=True, methods=["post"])
    def resolve(self, request, pk=None):
        """Mark an anomaly alert as resolved."""
        alert = self.get_object()
        serializer = AnomalyAlertResolveSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)

        alert.resolved = True
        alert.resolved_by = request.user

        if serializer.validated_data.get("resolution_note"):
            existing = alert.data_snapshot or {}
            existing["resolution_note"] = serializer.validated_data["resolution_note"]
            alert.data_snapshot = existing

        alert.save(update_fields=["resolved", "resolved_by", "data_snapshot"])

        return Response(
            AnomalyAlertSerializer(alert).data, status=status.HTTP_200_OK
        )

    @action(detail=True, methods=["post"])
    def explain(self, request, pk=None):
        """Use the LLM to generate a plain-English explanation of this anomaly."""
        alert = self.get_object()
        try:
            from apps.intelligence.services.llm_insights import explain_anomaly

            explanation = explain_anomaly(str(alert.id))
            return Response(
                {"anomaly_id": str(alert.id), "explanation": explanation},
                status=status.HTTP_200_OK,
            )
        except ImportError:
            return Response(
                {"detail": "LLM insights module is not available."},
                status=status.HTTP_501_NOT_IMPLEMENTED,
            )
        except Exception as exc:
            return Response(
                {"detail": f"LLM call failed: {exc}"},
                status=status.HTTP_500_INTERNAL_SERVER_ERROR,
            )


