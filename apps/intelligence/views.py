class IntelligenceDashboardViewSet(viewsets.ViewSet):
    """Aggregated endpoints that power the AI Intelligence dashboard.

    Not backed by a single model -- each ``@action`` queries across
    multiple intelligence tables.
    """

    permission_classes = [IsAuthenticated]

    # ------------------------------------------------------------------
    # Performance summary
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def performance(self, request):
        """Aggregated model performance for the AI dashboard.

        Returns per-model-type accuracy, total predictions (last 30 days),
        and the count of active model versions.
        """
        active_models = ModelVersion.objects.filter(is_active=True).annotate(
            pred_count=Count("predictions"),
            recent_preds=Count(
                "predictions",
                filter=Q(
                    predictions__created_at__gte=timezone.now()
                    - timedelta(days=30)
                ),
            ),
        )

        perf_rows = []
        for mv in active_models:
            accuracy = mv.accuracy_score

            # Fall back to live evaluation if available
            if accuracy is None:
                try:
                    from apps.intelligence.services.feedback_loop import evaluate_model

                    eval_result = evaluate_model(mv.model_type)
                    accuracy = eval_result.get("accuracy")
                except Exception:
                    accuracy = None

            perf_rows.append(
                {
                    "model_type": mv.model_type,
                    "model_type_display": mv.get_model_type_display(),
                    "version": mv.version,
                    "is_active": mv.is_active,
                    "accuracy": accuracy,
                    "total_predictions": mv.pred_count,
                    "recent_predictions_30d": mv.recent_preds,
                    "needs_retraining": accuracy is not None and accuracy < 0.7,
                    "last_trained": mv.last_trained_at or mv.created_at,
                }
            )

        # Top-level KPIs
        thirty_days_ago = timezone.now() - timedelta(days=30)
        total_preds_30d = PredictionLog.objects.filter(
            created_at__gte=thirty_days_ago
        ).count()
        unresolved_anomalies = AnomalyAlert.objects.filter(resolved=False).count()
        avg_accuracy = None
        accuracies = [r["accuracy"] for r in perf_rows if r["accuracy"] is not None]
        if accuracies:
            avg_accuracy = round(sum(accuracies) / len(accuracies), 4)

        return Response(
            {
                "kpis": {
                    "active_models": active_models.count(),
                    "total_predictions_30d": total_preds_30d,
                    "avg_accuracy": avg_accuracy,
                    "unresolved_anomalies": unresolved_anomalies,
                },
                "models": perf_rows,
            }
        )

    # ------------------------------------------------------------------
    # Dashboard summary stats
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def summary(self, request):
        """Quick counts for the dashboard cards."""
        thirty_days_ago = timezone.now() - timedelta(days=30)

        return Response(
            {
                "active_models": ModelVersion.objects.filter(is_active=True).count(),
                "total_predictions_30d": PredictionLog.objects.filter(
                    created_at__gte=thirty_days_ago
                ).count(),
                "unresolved_anomalies": AnomalyAlert.objects.filter(
                    resolved=False
                ).count(),
                "total_forecasts": DemandForecast.objects.count(),
                "critical_expiry_risks": ExpiryRiskAssessment.objects.filter(
                    risk_level="critical"
                ).count(),
                "high_expiry_risks": ExpiryRiskAssessment.objects.filter(
                    risk_level="high"
                ).count(),
                "low_adherence_patients": PatientAdherenceScore.objects.filter(
                    adherence_score__lt=50
                ).count(),
            }
        )

    # ------------------------------------------------------------------
    # Top demand forecasts (for dashboard table)
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def top_forecasts(self, request):
        """Return the latest forecast for each product, limited to top N."""
        limit = int(request.query_params.get("limit", 10))

        # Get latest forecast per product via subquery
        latest_per_product = (
            DemandForecast.objects.filter(product=OuterRef("product"))
            .order_by("-forecast_date")
        )

        forecasts = (
            DemandForecast.objects.filter(
                id=Subquery(latest_per_product.values("id")[:1])
            )
            .select_related("product", "model_version")
            .order_by("-predicted_quantity")[:limit]
        )

        serializer = DemandForecastSerializer(forecasts, many=True)
        return Response(serializer.data)

    # ------------------------------------------------------------------
    # Latest supplier scores (for dashboard table)
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def top_suppliers(self, request):
        """Return the latest score for each supplier, ordered by overall_score."""
        limit = int(request.query_params.get("limit", 10))

        latest_per_supplier = (
            SupplierScore.objects.filter(supplier=OuterRef("supplier"))
            .order_by("-calculated_at")
        )

        scores = (
            SupplierScore.objects.filter(
                id=Subquery(latest_per_supplier.values("id")[:1])
            )
            .select_related("supplier")
            .order_by("-overall_score")[:limit]
        )

        serializer = SupplierScoreSerializer(scores, many=True)
        return Response(serializer.data)

    # ------------------------------------------------------------------
    # Recent anomalies (for dashboard feed)
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def recent_anomalies(self, request):
        """Recent unresolved anomalies for the dashboard timeline."""
        limit = int(request.query_params.get("limit", 20))

        alerts = (
            AnomalyAlert.objects.filter(resolved=False)
            .select_related("resolved_by")
            .order_by("-created_at")[:limit]
        )

        serializer = AnomalyAlertSerializer(alerts, many=True)
        return Response(serializer.data)

    # ------------------------------------------------------------------
    # Expiry risk cards (for dashboard)
    # ------------------------------------------------------------------

    @action(detail=False, methods=["get"])
    def expiry_risks(self, request):
        """High/critical expiry risks for dashboard cards."""
        limit = int(request.query_params.get("limit", 12))

        risks = (
            ExpiryRiskAssessment.objects.filter(
                risk_level__in=["critical", "high"]
            )
            .select_related("lot__product")
            .order_by("-risk_score")[:limit]
        )

        serializer = ExpiryRiskAssessmentSerializer(risks, many=True)
        return Response(serializer.data)

    # ------------------------------------------------------------------
    # Trigger full pipeline
    # ------------------------------------------------------------------

    @action(detail=False, methods=["post"])
    def run_pipeline(self, request):
        """Execute the full intelligence pipeline and return results summary."""
        try:
            from apps.intelligence.services.run_pipeline import (
                run_full_intelligence_pipeline,
            )

            results = run_full_intelligence_pipeline()
            return Response(results, status=status.HTTP_200_OK)
        except ImportError:
            return Response(
                {"detail": "Pipeline module is not available."},
                status=status.HTTP_501_NOT_IMPLEMENTED,
            )
        except Exception as exc:
            return Response(
                {"detail": f"Pipeline execution failed: {exc}"},
                status=status.HTTP_500_INTERNAL_SERVER_ERROR,
            )

    # ------------------------------------------------------------------
    # LLM Insights
    # ------------------------------------------------------------------

    @action(detail=False, methods=["post"])
    def insights(self, request):
        """Trigger LLM-powered procurement recommendation or dashboard summary."""
        req_serializer = InsightRequestSerializer(data=request.data)
        req_serializer.is_valid(raise_exception=True)

        insight_type = req_serializer.validated_data["insight_type"]
        anomaly_id = req_serializer.validated_data.get("anomaly_id")
        supplier_ids = req_serializer.validated_data.get("supplier_ids", [])

        try:
            from apps.intelligence.services.llm_insights import (
                generate_procurement_recommendation,
                generate_dashboard_summary,
                explain_anomaly,
            )

            if insight_type == "procurement_recommendation":
                result = generate_procurement_recommendation()
            elif insight_type == "dashboard_summary":
                result = generate_dashboard_summary()
            elif insight_type == "anomaly_explanation":
                if not anomaly_id:
                    return Response(
                        {"detail": "anomaly_id is required for anomaly_explanation."},
                        status=status.HTTP_400_BAD_REQUEST,
                    )
                result = explain_anomaly(str(anomaly_id))
            else:
                return Response(
                    {"detail": f"Unknown insight_type: {insight_type}"},
                    status=status.HTTP_400_BAD_REQUEST,
                )

            return Response(
                {"insight_type": insight_type, "result": result},
                status=status.HTTP_200_OK,
            )
        except ImportError:
            return Response(
                {"detail": "LLM insights module is not available."},
                status=status.HTTP_501_NOT_IMPLEMENTED,
            )
        except Exception as exc:
            return Response(
                {"detail": f"LLM insight generation failed: {exc}"},
                status=status.HTTP_500_INTERNAL_SERVER_ERROR,
            )


