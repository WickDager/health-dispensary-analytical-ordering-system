# Theme Settings (for the frontend SettingsTheme page)
# ---------------------------------------------------------------------------
@api_view(["GET", "PATCH"])
@permission_classes([IsAuthenticated])
def theme_settings(request):
    """
    GET  /api/settings/theme/    → return theme preferences for the current user
    PATCH /api/settings/theme/   → update theme preferences for the current user
    """
    user = request.user

    # Return default preferences plus user's stored theme from Django User model
    prefs = {
        "theme": getattr(user, "theme_preference", "system"),
        "accent": "teal",
        "density": "comfortable",
        "font_size": "medium",
    }

    if request.method == "GET":
        return Response(prefs)

    # PATCH
    data = request.data
    theme = data.get("theme", prefs["theme"])
    if theme in ("light", "dark", "system"):
        if hasattr(user, "theme_preference"):
            user.theme_preference = theme
            user.save(update_fields=["theme_preference"])

    prefs.update({
        "theme": theme,
        "accent": data.get("accent", prefs["accent"]),
        "density": data.get("density", prefs["density"]),
        "font_size": data.get("font_size", prefs["font_size"]),
    })
    return Response(prefs)


