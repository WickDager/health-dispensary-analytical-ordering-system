# AI Settings configuration (for the frontend SettingsAI page)
# ---------------------------------------------------------------------------
@api_view(["GET", "PATCH"])
@permission_classes([IsAuthenticated])
def ai_settings(request):
    """
    GET  /api/settings/ai/    → returns all module configs + retraining schedule
    PATCH /api/settings/ai/   → update module configs and/or retraining schedule
    """
    import django.conf as _django_conf

    if request.method == "GET":
        modules = AIModuleConfig.objects.all()
        serializer = AIConfigSerializer({
            "modules": modules,
            "retraining_schedule": getattr(_django_conf.settings, "AI_RETRAINING_SCHEDULE", "weekly"),
        })
        return Response(serializer.data)

    # PATCH
    serializer = AIConfigSerializer(data=request.data)
    serializer.is_valid(raise_exception=True)

    modules_data = serializer.validated_data.get("modules", [])
    for mod in modules_data:
        AIModuleConfig.objects.update_or_create(
            key=mod["key"],
            defaults={
                "label": mod.get("label", ""),
                "description": mod.get("description", ""),
                "enabled": mod.get("enabled", True),
                "confidence_threshold": mod.get("confidence_threshold", 0.7),
            },
        )

    if "retraining_schedule" in serializer.validated_data:
        _django_conf.settings.AI_RETRAINING_SCHEDULE = serializer.validated_data["retraining_schedule"]

    modules = AIModuleConfig.objects.all()
    result = AIConfigSerializer({
        "modules": modules,
        "retraining_schedule": getattr(_django_conf.settings, "AI_RETRAINING_SCHEDULE", "weekly"),
    })
    return Response(result.data)


