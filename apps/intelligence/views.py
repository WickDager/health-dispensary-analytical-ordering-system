@api_view(["GET"])
@permission_classes([IsAuthenticated])
def user_settings_list(request):
    """GET /api/settings/users/ → list all users (admin-only view)."""
    if request.user.role != "ADMIN":
        return Response({"detail": "Admin access required."}, status=403)

    users = UserModel.objects.values(
        "id", "username", "email", "first_name", "last_name",
        "role", "is_active", "date_joined", "last_login",
    ).order_by("-date_joined")
    return Response(list(users))


@api_view(["PATCH"])
@permission_classes([IsAuthenticated])
def user_settings_detail(request, pk):
    """PATCH /api/settings/users/{id}/ → update user (activate/deactivate, change role)."""
    if request.user.role != "ADMIN":
        return Response({"detail": "Admin access required."}, status=403)

    try:
        user = UserModel.objects.get(pk=pk)
    except UserModel.DoesNotExist:
        return Response({"detail": "User not found."}, status=404)

    data = request.data
    if "is_active" in data:
        user.is_active = bool(data["is_active"])
    if "role" in data:
        new_role = data["role"].upper()
        valid_roles = [c[0] for c in UserModel._meta.get_field("role").choices]
        if new_role in valid_roles:
            user.role = new_role
        else:
            return Response({"detail": f"Invalid role: {data['role']}"}, status=400)

    update_fields = []
    if "is_active" in data:
        update_fields.append("is_active")
    if "role" in data:
        update_fields.append("role")
    user.save(update_fields=update_fields)
    return Response({"detail": "User updated."})
